#!/usr/bin/env python3
"""Generates UrllibTest/Idna/Vectors.lean from IdnaTestV2.txt.

Usage: python3 -I scripts/generate_idna_test_vectors.py IDNA_TEST_V2_FILE

Comments and blank lines are dropped, and so are the lines that contain an unpaired
surrogate escape, which a Lean string cannot represent. The columns are kept verbatim.
"""

import os
import re
import sys

SURROGATE = re.compile(r"\\u[dD][89a-fA-F][0-9a-fA-F]{2}|\\x\{[dD][89a-fA-F][0-9a-fA-F]{2}\}")


def main():
    source = sys.argv[1]
    lines = []
    skipped = 0
    with open(source, encoding="utf-8") as handle:
        for raw in handle:
            text = raw.rstrip("\n")
            if not text.strip() or text.startswith("#"):
                continue
            body = text.split("#", 1)[0]
            columns = [column.strip() for column in body.split(";")]
            if any(SURROGATE.search(column) for column in columns):
                skipped += 1
                continue
            lines.append(";".join(columns))
    escaped = "\\n".join(line.replace("\\", "\\\\").replace('"', '\\"') for line in lines)
    target = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "UrllibTest", "Idna", "Vectors.lean")
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, "w", encoding="utf-8") as handle:
        handle.write("-- Generated by scripts/generate_idna_test_vectors.py from IdnaTestV2.txt of Unicode 18.0.0; do not edit.\n\n")
        handle.write("namespace UrllibTest.Idna\n\n")
        handle.write("/-- The test lines of IdnaTestV2.txt: seven semicolon-separated columns per line. -/\n")
        handle.write(f"def vectors : String :=\n  \"{escaped}\"\n\n")
        handle.write(f"/-- The number of lines of IdnaTestV2.txt that carry an unpaired surrogate and are therefore left out. -/\n")
        handle.write(f"def skippedLines : Nat := {skipped}\n\n")
        handle.write("end UrllibTest.Idna\n")


if __name__ == "__main__":
    main()
