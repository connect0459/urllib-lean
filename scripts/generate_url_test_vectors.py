#!/usr/bin/env python3
"""Generates UrllibTest/Url/Vectors.lean from the Web Platform Tests file urltestdata.json.

Usage: python3 -I scripts/generate_url_test_vectors.py URLTESTDATA_JSON

Each test becomes one record of fourteen fields: input, base, outcome, href, protocol,
username, password, host, hostname, port, pathname, search, hash, origin. The base and the
origin are prefixed with S when present and N when null or absent; the outcome is F for a
failure and O otherwise. Fields are separated by a field separator and records by a record separator; both are private-use code points that no test contains, and the file defines them. Strings that
contain a lone surrogate, which a Lean string cannot represent, are skipped.
"""

import json
import os
import re
import sys

SURROGATE = re.compile("[\ud800-\udfff]")
KEYS = ["href", "protocol", "username", "password", "host", "hostname", "port", "pathname", "search", "hash"]


def optional(value):
    return "N" if value is None else "S" + value


def lean_escape(text):
    out = []
    for ch in text:
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif code < 0x20 or code == 0x7F:
            out.append("\\x%02x" % code)
        else:
            out.append(ch)
    return "".join(out)


def unused_code_points(data, count):
    used = set()
    for test in data:
        if isinstance(test, dict):
            for value in test.values():
                if isinstance(value, str):
                    used.update(ord(ch) for ch in value)
    found = []
    code = 0xE000
    while len(found) < count:
        if code not in used:
            found.append(chr(code))
        code += 1
    return found


def main():
    with open(sys.argv[1], encoding="utf-8") as handle:
        data = json.load(handle)
    FIELD, RECORD = unused_code_points(data, 2)
    records = []
    skipped = 0
    for test in data:
        if not isinstance(test, dict):
            continue
        values = [v for v in test.values() if isinstance(v, str)]
        if any(SURROGATE.search(v) for v in values):
            skipped += 1
            continue
        failure = bool(test.get("failure"))
        fields = [test["input"], optional(test["base"]), "F" if failure else "O"]
        fields += ["" if failure else test[key] for key in KEYS]
        fields.append(optional(None if failure else test.get("origin")))
        for field in fields:
            assert FIELD not in field and RECORD not in field
        records.append(FIELD.join(fields))
    body = lean_escape(RECORD.join(records))
    target = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "UrllibTest", "Url", "Vectors.lean")
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, "w", encoding="utf-8") as handle:
        handle.write("-- Generated by scripts/generate_url_test_vectors.py from urltestdata.json of the Web Platform Tests; do not edit.\n\n")
        handle.write("namespace UrllibTest.Url\n\n")
        handle.write(f"/-- Separates the fields of a record. -/\ndef fieldSeparator : Char := Char.ofNat {ord(FIELD)}\n\n")
        handle.write(f"/-- Separates the records. -/\ndef recordSeparator : Char := Char.ofNat {ord(RECORD)}\n\n")
        handle.write("/-- The records of urltestdata.json: fourteen fields separated by `fieldSeparator`, records separated by `recordSeparator`. -/\n")
        handle.write(f"def vectors : String :=\n  \"{body}\"\n\n")
        handle.write(f"/-- The number of tests that carry a lone surrogate and are therefore left out. -/\ndef skippedTests : Nat := {skipped}\n\n")
        handle.write("end UrllibTest.Url\n")


if __name__ == "__main__":
    main()
