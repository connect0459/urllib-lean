#!/usr/bin/env python3
"""Generates the Lean sources under Urllib/Unicode/Data from the Unicode Character Database.

Usage: python3 -I scripts/generate_unicode_data.py UCD_DIR

UCD_DIR must contain the following files of Unicode UNICODE_VERSION:
IdnaMappingTable.txt, UnicodeData.txt, DerivedNormalizationProps.txt,
DerivedBidiClass.txt, DerivedJoiningType.txt, DerivedCombiningClass.txt.
"""

import os
import re
import sys

UNICODE_VERSION = "18.0.0"
MAX = 0x10FFFF

STATUS = {
    "valid": "V",
    "mapped": "M",
    "deviation": "D",
    "disallowed": "X",
    "disallowed_STD3_valid": "V",
    "disallowed_STD3_mapped": "M",
    "ignored": "I",
}

BIDI_NAMES = {
    "Left_To_Right": "L",
    "Right_To_Left": "R",
    "Arabic_Letter": "AL",
    "European_Terminator": "ET",
}


def rows(path):
    with open(path, encoding="utf-8") as handle:
        for raw in handle:
            text = raw.split("#", 1)[0].strip()
            if not text:
                continue
            fields = [field.strip() for field in text.split(";")]
            span = fields[0].split("..")
            low = int(span[0], 16)
            high = int(span[-1], 16)
            yield low, high, fields[1:]


def merge(ranges):
    merged = []
    for low, high, value in ranges:
        if merged and merged[-1][2] == value and merged[-1][1] + 1 == low:
            merged[-1] = (merged[-1][0], high, value)
        else:
            merged.append((low, high, value))
    return merged


def hex_(value):
    return f"{value:X}"


def lean_module(namespace_doc, name, body):
    return (
        f"/-- {namespace_doc} -/\n"
        f"def {name} : String :=\n"
        f"  \"{body}\"\n"
    )


def write(path, definitions):
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(f"-- Generated by scripts/generate_unicode_data.py from Unicode {UNICODE_VERSION}; do not edit.\n\n")
        handle.write(f"namespace Urllib.Unicode.Data\n\n")
        handle.write("\n".join(definitions))
        handle.write("\nend Urllib.Unicode.Data\n")


def mapping(ucd):
    ranges = []
    for low, high, fields in rows(os.path.join(ucd, "IdnaMappingTable.txt")):
        status = STATUS[fields[0]]
        target = ""
        if status in ("M", "D"):
            target = fields[1] if len(fields) > 1 else ""
            target = " ".join(target.split())
        ranges.append((low, high, (status, target)))
    ranges.sort()
    lines = []
    for low, high, (status, target) in merge(ranges):
        lines.append(" ".join(part for part in (hex_(low), hex_(high), status, target) if part))
    return "\\n".join(lines)


def combining_classes(ucd):
    ranges = []
    for low, high, fields in rows(os.path.join(ucd, "DerivedCombiningClass.txt")):
        value = int(fields[0])
        if value != 0:
            ranges.append((low, high, value))
    ranges.sort()
    return "\\n".join(f"{hex_(low)} {hex_(high)} {value}" for low, high, value in merge(ranges))


def unicode_data(ucd):
    entries = []
    with open(os.path.join(ucd, "UnicodeData.txt"), encoding="utf-8") as handle:
        for raw in handle:
            fields = raw.rstrip("\n").split(";")
            entries.append(fields)
    return entries


def composition_exclusions(ucd):
    excluded = set()
    with open(os.path.join(ucd, "DerivedNormalizationProps.txt"), encoding="utf-8") as handle:
        for raw in handle:
            text = raw.split("#", 1)[0].strip()
            if not text:
                continue
            fields = [field.strip() for field in text.split(";")]
            if len(fields) >= 2 and fields[1] == "Full_Composition_Exclusion":
                span = fields[0].split("..")
                for cp in range(int(span[0], 16), int(span[-1], 16) + 1):
                    excluded.add(cp)
    return excluded


def decompositions(ucd):
    excluded = composition_exclusions(ucd)
    one_level = {}
    composition_pairs = []
    for fields in unicode_data(ucd):
        mapping_field = fields[5]
        if not mapping_field or mapping_field.startswith("<"):
            continue
        cp = int(fields[0], 16)
        parts = [int(part, 16) for part in mapping_field.split()]
        one_level[cp] = parts
        if len(parts) == 2 and cp not in excluded:
            composition_pairs.append((parts[0], parts[1], cp))

    def expand(cp):
        if cp not in one_level:
            return [cp]
        return [leaf for part in one_level[cp] for leaf in expand(part)]

    decomposition_lines = [" ".join(hex_(v) for v in [cp] + expand(cp)) for cp in sorted(one_level)]
    composition_pairs.sort()
    composition_lines = [" ".join(hex_(v) for v in pair) for pair in composition_pairs]
    return "\\n".join(decomposition_lines), "\\n".join(composition_lines)


def marks(ucd):
    ranges = []
    for fields in unicode_data(ucd):
        if fields[2] in ("Mn", "Mc", "Me"):
            cp = int(fields[0], 16)
            ranges.append((cp, cp, "M"))
    ranges.sort()
    return "\\n".join(f"{hex_(low)} {hex_(high)}" for low, high, _ in merge(ranges))


def bidi_classes(ucd):
    classes = [None] * (MAX + 1)
    path = os.path.join(ucd, "DerivedBidiClass.txt")
    missing = []
    with open(path, encoding="utf-8") as handle:
        for raw in handle:
            match = re.match(r"^# @missing: ([0-9A-F]+)\.\.([0-9A-F]+); (\w+)", raw)
            if match:
                missing.append((int(match.group(1), 16), int(match.group(2), 16), BIDI_NAMES[match.group(3)]))
    for low, high, value in missing:
        for cp in range(low, high + 1):
            classes[cp] = value
    for low, high, fields in rows(path):
        for cp in range(low, high + 1):
            classes[cp] = fields[0]
    ranges = [(cp, cp, value) for cp, value in enumerate(classes)]
    return "\\n".join(f"{hex_(low)} {hex_(high)} {value}" for low, high, value in merge(ranges))


def joining_types(ucd):
    ranges = []
    for low, high, fields in rows(os.path.join(ucd, "DerivedJoiningType.txt")):
        if fields[0] in ("L", "R", "D", "T"):
            ranges.append((low, high, fields[0]))
    ranges.sort()
    return "\\n".join(f"{hex_(low)} {hex_(high)} {value}" for low, high, value in merge(ranges))


def main():
    ucd = sys.argv[1]
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Urllib", "Unicode", "Data")
    os.makedirs(root, exist_ok=True)
    write(
        os.path.join(root, "IdnaMapping.lean"),
        [lean_module(
            f"The IDNA mapping table of Unicode {UNICODE_VERSION}: lines `low high status [target]` in hexadecimal; status V valid, M mapped, D deviation, X disallowed, I ignored.",
            "idnaMapping", mapping(ucd))],
    )
    decomposition, composition = decompositions(ucd)
    write(
        os.path.join(root, "Normalization.lean"),
        [
            lean_module("Non-zero canonical combining classes: lines `low high class`.", "combiningClasses", combining_classes(ucd)),
            lean_module("Full canonical decompositions: lines `code point` followed by its fully decomposed code points.", "canonicalDecompositions", decomposition),
            lean_module("Primary composites: lines `first second composite`, sorted by the pair.", "compositionPairs", composition),
        ],
    )
    write(
        os.path.join(root, "Properties.lean"),
        [
            lean_module("Ranges of code points with General_Category Mark: lines `low high`.", "markRanges", marks(ucd)),
            lean_module("Bidi_Class of every code point, in ranges: lines `low high class`.", "bidiClasses", bidi_classes(ucd)),
            lean_module("Joining_Type L, R, D, and T ranges: lines `low high type`.", "joiningTypes", joining_types(ucd)),
        ],
    )


if __name__ == "__main__":
    main()
