#!/usr/bin/env python3
"""Generates UrllibTest/UrlPattern/Vectors.lean from urlpatterntestdata.json of the Web Platform Tests.

Usage: python3 -I scripts/generate_urlpattern_vectors.py URLPATTERNTESTDATA_JSON URLPATTERN_COMPARE_JSON URLPATTERN_GENERATE_JSON

The tests are kept as JSON text in a Lean string, and the Lean tests parse it with Lean.Json.
Comments are dropped, and so are the entries that contain a lone surrogate, which a Lean string
cannot represent.
"""

import json
import os
import re
import sys

SURROGATE = re.compile("[\ud800-\udfff]")


def lean_escape(text):
    out = []
    for ch in text:
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif code < 0x20 or code == 0x7F:
            out.append("\\x%02x" % code)
        else:
            out.append(ch)
    return "".join(out)


def has_surrogate(value):
    if isinstance(value, str):
        return bool(SURROGATE.search(value))
    if isinstance(value, dict):
        return any(has_surrogate(k) or has_surrogate(v) for k, v in value.items())
    if isinstance(value, list):
        return any(has_surrogate(v) for v in value)
    return False


def main():
    with open(sys.argv[1], encoding="utf-8") as handle:
        data = json.load(handle)
    kept = [entry for entry in data if isinstance(entry, dict) and not has_surrogate(entry)]
    skipped = len([entry for entry in data if isinstance(entry, dict)]) - len(kept)
    target = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "UrllibTest", "UrlPattern", "Vectors.lean")
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, "w", encoding="utf-8") as handle:
        handle.write("-- Generated by scripts/generate_urlpattern_vectors.py from urlpatterntestdata.json of the Web Platform Tests; do not edit.\n\n")
        handle.write("namespace UrllibTest.UrlPattern\n\n")
        handle.write("/-- The tests of urlpatterntestdata.json as JSON text. -/\n")
        handle.write(f"def vectors : String :=\n  \"{lean_escape(json.dumps(kept, ensure_ascii=False))}\"\n\n")
        handle.write(f"/-- The number of tests that carry a lone surrogate and are therefore left out. -/\ndef skippedTests : Nat := {skipped}\n")
        for argument, name, doc in ((2, "compareVectors", "urlpattern-compare-test-data.json"),
                                    (3, "generateVectors", "urlpattern-generate-test-data.json")):
            with open(sys.argv[argument], encoding="utf-8") as extra_handle:
                extra = json.load(extra_handle)
            handle.write(f"\n/-- The tests of {doc} as JSON text. -/\n")
            handle.write(f"def {name} : String :=\n  \"{lean_escape(json.dumps(extra, ensure_ascii=False))}\"\n")
        handle.write("\nend UrllibTest.UrlPattern\n")


if __name__ == "__main__":
    main()
