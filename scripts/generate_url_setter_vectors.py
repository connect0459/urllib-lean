#!/usr/bin/env python3
"""Generates UrllibTest/Url/SetterVectors.lean from the Web Platform Tests files setters_tests.json and toascii.json.

Usage: python3 -I scripts/generate_url_setter_vectors.py SETTERS_TESTS_JSON TOASCII_JSON

A setter test becomes one record: the setter name, the starting href, the new value, and the
expected key-value pairs flattened after them. A toascii test becomes one record: the input and
the output, prefixed with S when present and N when null. Fields are separated by a field
separator and records by a record separator; both are private-use code points that no test
contains, and the file defines them. Strings with a lone surrogate are skipped.
"""

import json
import os
import re
import sys

SURROGATE = re.compile("[\ud800-\udfff]")


def lean_escape(text):
    out = []
    for ch in text:
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif code < 0x20 or code == 0x7F:
            out.append("\\x%02x" % code)
        else:
            out.append(ch)
    return "".join(out)


def strings_of(value):
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for item in value.values():
            yield from strings_of(item)
    elif isinstance(value, list):
        for item in value:
            yield from strings_of(item)


def main():
    with open(sys.argv[1], encoding="utf-8") as handle:
        setters = json.load(handle)
    with open(sys.argv[2], encoding="utf-8") as handle:
        toascii = json.load(handle)
    used = set()
    for value in (setters, toascii):
        for text in strings_of(value):
            used.update(ord(ch) for ch in text)
    separators = []
    code = 0xE000
    while len(separators) < 2:
        if code not in used:
            separators.append(chr(code))
        code += 1
    field, record = separators
    skipped = 0
    setter_records = []
    for group, tests in setters.items():
        if group == "comment":
            continue
        for test in tests:
            if any(SURROGATE.search(text) for text in strings_of(test)):
                skipped += 1
                continue
            fields = [group, test["href"], test["new_value"]]
            for key, value in test["expected"].items():
                fields += [key, value]
            setter_records.append(field.join(fields))
    ascii_records = []
    for test in toascii:
        if not isinstance(test, dict):
            continue
        if any(SURROGATE.search(text) for text in strings_of(test)):
            skipped += 1
            continue
        output = test["output"]
        ascii_records.append(field.join([test["input"], "N" if output is None else "S" + output]))
    target = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "UrllibTest", "Url", "SetterVectors.lean")
    with open(target, "w", encoding="utf-8") as handle:
        handle.write("-- Generated by scripts/generate_url_setter_vectors.py from setters_tests.json and toascii.json of the Web Platform Tests; do not edit.\n\n")
        handle.write("namespace UrllibTest.Url\n\n")
        handle.write(f"/-- Separates the fields of a setter or toascii record. -/\ndef setterFieldSeparator : Char := Char.ofNat {ord(field)}\n\n")
        handle.write(f"/-- Separates the records. -/\ndef setterRecordSeparator : Char := Char.ofNat {ord(record)}\n\n")
        handle.write("/-- The tests of setters_tests.json: the setter, the href, the new value, then key-value pairs of expected values. -/\n")
        handle.write(f"def setterVectors : String :=\n  \"{lean_escape(record.join(setter_records))}\"\n\n")
        handle.write("/-- The tests of toascii.json: the input and the output, which is S followed by the output or N for a failure. -/\n")
        handle.write(f"def toasciiVectors : String :=\n  \"{lean_escape(record.join(ascii_records))}\"\n\n")
        handle.write(f"/-- The number of tests with a lone surrogate that are left out. -/\ndef skippedSetterTests : Nat := {skipped}\n\n")
        handle.write("end UrllibTest.Url\n")


if __name__ == "__main__":
    main()
